def get_ui_translations(config=None, ui_lang=None):
    """Retourne le dict i18n pour la langue d'interface.

    Priorité : ``ui_lang`` explicite > ``config['UI_LANG']`` > ``load_config()``.
    Passer ``config=`` (ou ``ui_lang=``) depuis ``load_config`` pour éviter toute
    récursion pendant le chargement.
    """
    lang = ""
    if ui_lang is not None:
        lang = str(ui_lang).strip()
    if not lang and isinstance(config, dict):
        lang = str(config.get("UI_LANG") or "").strip()
    if not lang:
        try:
            from config_manager import load_config
            lang = str(load_config().get("UI_LANG") or "").strip()
        except Exception:
            lang = ""
    lang = (lang or "fr").lower()[:2]
    return translations.get(lang, translations["fr"])


